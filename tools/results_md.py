"""results/R*.json -> docs/RESULTS.md (the result tables quoted by the dossier). `--check` fails if stale."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def R(k):
    return json.loads((ROOT / "results" / f"{k}.json").read_text(encoding="utf-8"))


def f(x, n=2):
    if x is None or x == "inf" or (isinstance(x, float) and x != x):
        return "unbounded"
    if isinstance(x, float) and x == float("inf"):
        return "unbounded"
    return f"{x:.{n}f}"


def _raw(c, x):
    if c == "reliability":
        return f"F {x:.2e}"
    return f(x, 3) if isinstance(x, float) else x


def render() -> str:
    L = ["# Results (generated)", "", "Generated by `python tools/results_md.py` from `results/R*.json` (`python -m vnet all`). Do not edit.", ""]
    r1 = R("R1")
    L += ["## R1 Published CAN benchmark reproduced [DAVIS2007 Table 2, section 4.2]", "",
          "| Message | Legacy analysis (published 2/3/3 ms) | Revised analysis | Simulation, critical instant |", "|---|---|---|---|"]
    for k in "ABC":
        L.append(f"| {k} | {f(r1['legacy_ms'][k])} | {f(r1['revised_ms'][k])} | {f(r1['sim_critical_instant_ms'][k], 3)} |")
    L += ["", f"Busy period of C {f(r1['busy_C_ms'], 1)} ms with {r1['Q_C']} instances (published 7.0 ms, 2). "
          "Breakdown utilisation of the legacy analysis, messages: % (published 45.5 / 21.4 / 9.2 / 3.4 / 0.82): "
          + ", ".join(f"{n}: {v}" for n, v in r1["breakdown_pct"].items()) + ".", ""]
    r2 = R("R2")
    L += ["## R2 Frame lengths: bit-level stuffing vs the Eq. (1) bound (random identifiers and payloads)", "",
          "| Frame | Bound (bits) | Max seen | Mean | p99 |", "|---|---|---|---|---|"]
    for k, v in r2.items():
        L.append(f"| {k} | {v['bound']} | {v['max']} | {f(v['mean'], 1)} | {f(v['p99'], 0)} |")
    L.append("")
    r3 = R("R3")
    L += ["## R3 Worst-case response-time analysis per architecture", "",
          "| Arch | Bus | Rate | Growth | Errors | Frames | Load % | Misses | STEER_CMD ms | INS_DYN ms | NAV_POS ms |",
          "|---|---|---|---|---|---|---|---|---|---|---|"]
    for a, d in r3.items():
        for row in d["rows"]:
            rr = row["R_ms"]
            L.append(f"| {a} | {row['bus']}{' x2' if row['dual'] else ''} | {row['bps'] // 1000}k{' FD' if row['kind'] == 'canfd' else ''} | "
                     f"{'+30 %' if row['growth'] else '-'} | {'yes' if row['errors'] else '-'} | {row['n']} | {f(100 * row['load'], 1)} | "
                     f"{len(row['misses'])} | {f(rr.get('STEER_CMD')) if 'STEER_CMD' in rr else ''} | "
                     f"{f(rr.get('INS_DYN')) if 'INS_DYN' in rr else ''} | {f(rr.get('NAV_POS')) if 'NAV_POS' in rr else ''} |")
    L.append("")
    r4 = R("R4")
    for k, d in r4.items():
        L += [f"## R4 Simulator vs analysis, {k} ({d['bps'] // 1000} kbit/s)", "",
              "| Message | Bound ms | Critical instant ms | Random phasing max ms |", "|---|---|---|---|"]
        for row in d["rows"]:
            L.append(f"| {row['msg']} | {f(row['bound_ms'], 3)} | {f(row['critical_instant_ms'], 3)} | {f(row['random_max_ms'], 3)} |")
        L.append("")
    r5 = R("R5")
    v = r5["vehicle"]
    a = r5["actuator_loop"]
    L += ["## R5 Steering loops: margins vs speed", "",
          f"Vehicle: {v['mass'] / 1000:.0f} t, wheelbase {v['wheelbase']:.2f} m, effective wheelbase {v['l_eff']:.2f} m, "
          f"understeer gradient {v['Kus_deg_per_g']:.2f} deg/g. L1 (position loop across the network): crossover {a['wc']:.1f} rad/s, "
          f"PM {a['pm_deg']:.1f} deg, delay margin {a['dm_s'] * 1e3:.0f} ms, delay for PM 30 deg {a['t30_s'] * 1e3:.1f} ms.", "",
          "| km/h | Yaw damping | L2 PM deg | L2 delay margin ms | L2 delay for PM 30 deg ms | L3 crossover rad/s | L3 PM deg | L3 delay for PM 30 deg ms |",
          "|---|---|---|---|---|---|---|---|"]
    for s in r5["speeds"]:
        y, p = s["yaw"], s["path"]
        L.append(f"| {s['kmh']} | {f(s['yaw_damping'])} | {f(y['pm_deg'], 1)} | {f(y['dm_s'] * 1e3, 0)} | {f(y['t30_s'] * 1e3, 1)} | "
                 f"{f(p['wc'])} | {f(p['pm_deg'], 1)} | {f(p['t30_s'] * 1e3, 0)} |")
    L += ["", "Time-domain check (delay at which the closed loop stops converging, 1 ms sampling):", "",
          "| km/h | L2 delay margin ms | L2 simulated ms | L3 delay margin ms | L3 simulated ms |", "|---|---|---|---|---|"]
    for x in r5["verification"]:
        L.append(f"| {x['kmh']} | {f(x['yaw_dm_ms'], 1)} | {f(x['yaw_sim_ms'], 1)} | {f(x['path_dm_ms'], 0)} | {f(x['path_sim_ms'], 0)} |")
    L.append("")
    r6 = R("R6")
    b = r6["budgets_ms"]
    L += ["## R6 End-to-end chains (growth + error model)", "",
          f"Budgets = 50 % of the delay for PM 30 deg at 120 km/h: YAW {f(b['YAW'], 1)} ms, ACT_CENTRAL {f(b['ACT_CENTRAL'], 1)} ms, "
          f"PATH {f(b['PATH'], 1)} ms; driver chains 50 ms.", "",
          "| Arch | YAW | ACT_CENTRAL | PATH | DRIVER_STEER | DRIVER_BRAKE |", "|---|---|---|---|---|---|"]
    for arch, cs in r6["archs"].items():
        d = {c["chain"]: c for c in cs}
        L.append(f"| {arch} | " + " | ".join(f"{f(d[k]['total_ms'], 1)}{'' if d[k]['ok'] else ' OVER'}" for k in
                                              ("YAW", "ACT_CENTRAL", "PATH", "DRIVER_STEER", "DRIVER_BRAKE")) + " |")
    sp = r6["A2_yaw_split_ms"]
    L += ["", f"A2 yaw chain split: bus {f(sp['bus'], 2)} ms, task periods {f(sp['tasks'], 1)} ms.", "",
          "VCU period sweep (by-wire frames follow the VCU period), yaw chain ms / by-wire bus load % / misses:", "",
          "| Arch | 2 ms | 5 ms | 10 ms | 20 ms |", "|---|---|---|---|---|"]
    for arch, sw in r6["vcu_period_sweep_yaw_ms"].items():
        ld = r6["vcu_period_sweep_bw_load"][arch]
        L.append(f"| {arch} | " + " | ".join(f"{f(sw[p], 1)} / {f(100 * ld[p]['load'], 0)} / {ld[p]['misses']}" for p in ("2", "5", "10", "20")) + " |")
    L.append("")
    r7 = R("R7")
    for k, d in r7.items():
        L += [f"## R7 Ethernet backbone {k}: network-calculus bound vs simulation (max port load {f(100 * d['max_port_load'], 1)} %)", "",
              "| Flow | PCP | Bound ms | Aligned sim ms | Random sim ms | Deadline ms |", "|---|---|---|---|---|---|"]
        for x in d["flows"]:
            L.append(f"| {x['flow']} | {x['pcp']} | {f(x['bound_ms'], 3)} | {f(x['aligned_ms'], 3)} | {f(x['sim_ms'], 3)} | {f(x['deadline_ms'], 0)} |")
        L.append("")
    r8 = R("R8")
    L += ["## R8 Faults", "", "| Bit rate | Frames to error passive | Frames to bus-off | Time to bus-off ms | Recovery min ms | With app delay ms |",
          "|---|---|---|---|---|---|"]
    for bps, c in r8["confinement"].items():
        L.append(f"| {int(bps) // 1000}k | {c['frames_to_passive']} | {c['frames_to_bus_off']} | {f(c['t_bus_off_ms'], 1)} | "
                 f"{f(c['t_recover_min_ms'], 2)} | {f(c['t_recover_app_ms'], 1)} |")
    L += ["", "Shortest babbling period that leaves every message schedulable (ms): "
          + ", ".join(f"{k}: {f(v)}" for k, v in r8["babbler_min_period_ms"].items()) + ".", "",
          "Dual-channel run: " + "; ".join(f"t={t} ms {e}" for t, e in r8["events"]) + ". States: "
          + ", ".join(f"{s} from {t} ms" for t, s in r8["redundancy_states"]) + ". Max set-point age per state (ms): "
          + ", ".join(f"{k} {v}" for k, v in sorted(r8["max_age_by_state_ms"].items())) + ".", ""]
    r9 = R("R9")
    L += ["## R9 Reliability of the steer-command path (12 h)", "", "| Arch | Nodes on channel | lambda per channel /h | F(12 h) | per hour | MTTF h |",
          "|---|---|---|---|---|---|"]
    for k, p in r9["paths"].items():
        L.append(f"| {k} | {p['nodes_on_channel']} | {p['lambda_channel_per_h']:.2e} | {p['F_mission']:.2e} | {p['F_mission'] / 12:.2e} | {p['MTTF_h']:.3g} |")
    L += ["", "Common-cause beta sweep, A2 F(12 h): " + ", ".join(f"beta {k}: {v:.2e}" for k, v in r9["beta_sweep_A2"].items()) + ".",
          "Failure-rate scale sweep F(12 h): " + "; ".join(f"{a}: " + ", ".join(f"{k} {v:.1e}" for k, v in d.items()) for a, d in r9["scale_sweep"].items()) + ".", ""]
    r10 = R("R10")
    L += ["## R10 Trade study", "", "Screening:", ""]
    for a, rs in r10["screen"].items():
        L.append(f"- {a}: {'; '.join(rs) if rs else 'passes'}")
    L += ["", "| Criterion | Weight | " + " | ".join(r10["fom"]) + " |", "|---|---|" + "---|" * len(r10["fom"])]
    for c, w in r10["weights"].items():
        L.append(f"| {c} | {f(w, 3)} | " + " | ".join(f"{_raw(c, r10['raw'][a][c])} "
                                                       f"(u {f(r10['utility'][a][c], 2)})" for a in r10["fom"]) + " |")
    L.append("| **Figure of merit** | | " + " | ".join(f"**{f(v, 3)}**" for v in r10["fom"].values()) + " |")
    L += ["", f"Leader {r10['leader']}. -10 % weight sensitivity winners: " + ", ".join(f"{s['criterion']} -> {s['winner']}" for s in r10["sensitivity"])
          + ". Random weights (x U(0.5, 1.5), 2000 draws) wins: " + ", ".join(f"{k} {100 * v:.1f} %" for k, v in r10["monte_carlo"].items()) + ".",
          "Rating at which a rival overtakes the leader (current ratings in data/aoa.yaml): "
          + "; ".join(f"{r}: " + ", ".join(f"{k} {f(v, 2)}" for k, v in d.items() if v != float("inf") and v != "inf") for r, d in r10["crossover_rating"].items()) + ".", ""]
    r11 = R("R11")
    L += ["## R11 Physical layer", "", "| Bit rate | Arbitration round-trip length limit m |", "|---|---|"]
    for x in r11["rows"]:
        L.append(f"| {x['bps'] // 1000}k | {f(x['arbitration_limit_m'], 0)} |")
    L += ["", f"Reference harness {r11['harness_m']} m; J1939 limits: " + "; ".join(f"{k} {v['max_bus_m']} m, stubs {v['max_stub_m']} m, {v['max_nodes']} nodes"
                                                                              for k, v in r11["j1939"].items()) + ".", ""]
    r12 = R("R12")
    t = r12["t30_ms"]
    L += ["## R12 Uncertainty: yaw-loop delay for PM 30 deg at 120 km/h", "",
          f"{r12['n']} samples of mass 20-33 t, cornering coefficient 4-8 /rad, compliance 0.7-1.0, actuator 2-5 Hz, radius of gyration "
          f"1.9-2.4 m, loop crossover 5-7 rad/s: P5 {f(t['p5'], 1)} ms, median {f(t['p50'], 1)} ms, min {f(t['min'], 1)} ms.", "",
          "| Case | Chain ms | P(chain <= delay for PM 30) | P(chain <= half of it) |", "|---|---|---|---|"]
    for k, c in r12["cases"].items():
        L.append(f"| {k} | {f(c['chain_ms'], 1)} | {f(c['P_within_t30'], 2)} | {f(c['P_within_half_t30'], 2)} |")
    L.append("")
    return "\n".join(L)


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = render()
    p = ROOT / "docs" / "RESULTS.md"
    if a.check:
        ok = p.exists() and p.read_text(encoding="utf-8") == text
        print("docs/RESULTS.md is current" if ok else "docs/RESULTS.md is out of date: run python tools/results_md.py")
        return 0 if ok else 1
    p.write_text(text, encoding="utf-8", newline="\n")
    print("wrote", p.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
