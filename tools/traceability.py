"""Build docs/traceability.md from the @pytest.mark.req(...) markers in tests/.

`--check` fails when the checked-in file is out of date or a DOSSIER requirement has no test.
"""
from __future__ import annotations

import argparse
import ast
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def _marks(node) -> tuple[list[str], str | None]:
    reqs, it = [], None
    decs = node.decorator_list if hasattr(node, "decorator_list") else [node]
    for d in decs:
        if isinstance(d, ast.Call) and isinstance(d.func, ast.Attribute):
            name = d.func.attr
            args = [a.value for a in d.args if isinstance(a, ast.Constant)]
            if name == "req":
                reqs += args
            elif name == "it" and args:
                it = args[0]
    return reqs, it


def collect() -> dict[str, list[str]]:
    out: dict[str, list[str]] = {}
    for f in sorted((ROOT / "tests").rglob("test_*.py")):
        tree = ast.parse(f.read_text(encoding="utf-8"))
        module_reqs: list[str] = []
        for node in tree.body:
            if isinstance(node, ast.Assign) and any(getattr(t, "id", "") == "pytestmark" for t in node.targets):
                module_reqs += _marks(node.value)[0]
        rel = f.relative_to(ROOT).as_posix()
        for node in tree.body:
            if isinstance(node, ast.FunctionDef) and node.name.startswith("test_"):
                reqs, it = _marks(node)
                label = f"`{rel}::{node.name}`" + (f" ({it})" if it else "")
                for r in sorted(set(reqs + module_reqs)):
                    out.setdefault(r, []).append(label)
    return out


def spec_requirements() -> dict[str, str]:
    text = (ROOT / "DOSSIER.md").read_text(encoding="utf-8")
    out: dict[str, str] = {}
    for m in re.finditer(r"^\| ((?:SR|MS)-\d\d) \| (.+?) \|", text, re.M):
        out.setdefault(m.group(1), m.group(2).strip())   # the requirements table comes first
    return out


def render() -> tuple[str, list[str]]:
    reqs = spec_requirements()
    tests = collect()
    lines = ["# Traceability: requirement -> tests", "",
             "Generated by `python tools/traceability.py` from the `@pytest.mark.req(...)` markers. Do not edit.", "",
             "| Req | Requirement | Tests |", "|---|---|---|"]
    missing = []
    for rid, text in reqs.items():
        t = tests.get(rid, [])
        if not t:
            missing.append(rid)
        short = text if len(text) < 90 else text[:87] + "..."
        lines.append(f"| {rid} | {short} | {'<br>'.join(t) if t else '**none**'} |")
    lines.append("")
    return "\n".join(lines), missing


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text, missing = render()
    p = ROOT / "docs" / "traceability.md"
    if a.check:
        bad = not p.exists() or p.read_text(encoding="utf-8") != text
        if bad:
            print("docs/traceability.md is out of date: run python tools/traceability.py")
        if missing:
            print("requirements without a test:", ", ".join(missing))
        return 1 if bad or missing else 0
    p.parent.mkdir(exist_ok=True)
    p.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {p.relative_to(ROOT)}; requirements without a test: {missing or 'none'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
